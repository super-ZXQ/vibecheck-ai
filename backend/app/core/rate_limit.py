"""Token-bucket limits for the two task-creating endpoints.

`POST /api/check` and `POST /api/check/upload` are the only requests whose work
outlives the response. Admission coalesces the same repository into one pending
slot, but `X-Submitter-Key` is generated by the client and costs nothing to
mint, so without a limit one caller can claim every pending slot with fresh
keys.

Two buckets must both allow a submission:

- client IP — the anchor an anonymous caller cannot mint. It is the TCP peer
  unless a reverse proxy is in front and uvicorn is told to trust its headers
  (`FORWARDED_ALLOW_IPS`, see docs/PUBLIC_DEPLOYMENT.md).
- submitter key — per-browser friction, so one tab cannot cycle repositories
  quickly. A fresh key still has to pass the IP bucket.

Tokens refill continuously, which lets a rejection return an accurate
`Retry-After`. State is process memory, matching the single-uvicorn-worker
execution model; a restart resets the budget.
"""

from __future__ import annotations

import math
import time
from collections.abc import Callable
from dataclasses import dataclass

from fastapi import Request
from fastapi.responses import JSONResponse
from starlette.middleware.base import BaseHTTPMiddleware, RequestResponseEndpoint
from starlette.responses import Response

from app.core.config import Settings, settings
from app.core.error_codes import RATE_LIMITED, get_error_message
from app.services import metrics as metrics_mod

# Only these two routes create tasks. Status polling is a GET and must stay
# unthrottled: the frontend polls every few seconds while a scan runs.
SUBMISSION_PATHS = frozenset({"/api/check", "/api/check/upload"})

_PRUNE_INTERVAL_SECONDS = 60.0
_MAX_BUCKETS = 4096


@dataclass
class _BucketState:
    tokens: float
    updated_at: float


class TokenBucket:
    """Continuous-refill bucket keyed by an arbitrary string."""

    def __init__(
        self,
        rate_per_minute: int,
        burst: int,
        *,
        clock: Callable[[], float] = time.monotonic,
        max_buckets: int = _MAX_BUCKETS,
    ) -> None:
        if rate_per_minute < 1 or burst < 1:
            raise ValueError("rate_per_minute and burst must be >= 1")
        self._rate_per_second = rate_per_minute / 60.0
        self._burst = float(burst)
        self._clock = clock
        self._max_buckets = max_buckets
        self._buckets: dict[str, _BucketState] = {}
        # An untouched bucket has fully refilled after burst/rate seconds; add
        # slack so pruning can never forget a bucket that is still partial.
        self._idle_seconds = max(120.0, 2.0 * self._burst / self._rate_per_second)
        self._next_prune_at = clock() + _PRUNE_INTERVAL_SECONDS

    def retry_after(self, key: str, now: float | None = None) -> float:
        """Seconds until one token is available; 0.0 means the request fits."""
        now = self._clock() if now is None else now
        state = self._state(key, now)
        if state.tokens >= 1.0:
            return 0.0
        return (1.0 - state.tokens) / self._rate_per_second

    def consume(self, key: str, now: float | None = None) -> None:
        """Take one token. Callers must have seen retry_after() == 0.0."""
        now = self._clock() if now is None else now
        state = self._state(key, now)
        if state.tokens >= 1.0:
            state.tokens -= 1.0

    def bucket_count(self) -> int:
        return len(self._buckets)

    def _state(self, key: str, now: float) -> _BucketState:
        state = self._buckets.get(key)
        if state is None:
            state = _BucketState(tokens=self._burst, updated_at=now)
            self._buckets[key] = state
        else:
            elapsed = now - state.updated_at
            if elapsed > 0:
                state.tokens = min(self._burst, state.tokens + elapsed * self._rate_per_second)
                state.updated_at = now
        self._maybe_prune(now)
        return state

    def _maybe_prune(self, now: float) -> None:
        if now < self._next_prune_at and len(self._buckets) <= self._max_buckets:
            return
        self._next_prune_at = now + _PRUNE_INTERVAL_SECONDS

        idle_before = now - self._idle_seconds
        stale = [key for key, state in self._buckets.items() if state.updated_at < idle_before]
        for key in stale:
            del self._buckets[key]

        overflow = len(self._buckets) - self._max_buckets
        if overflow > 0:
            oldest = sorted(self._buckets, key=lambda k: self._buckets[k].updated_at)
            for key in oldest[:overflow]:
                del self._buckets[key]


@dataclass(frozen=True)
class RateLimitDecision:
    allowed: bool
    retry_after: int = 0


class SubmissionRateLimiter:
    """Two-tier limiter: both the client IP and the submitter key must allow."""

    def __init__(
        self,
        *,
        ip_per_minute: int,
        ip_burst: int,
        submitter_per_minute: int,
        submitter_burst: int,
        clock: Callable[[], float] = time.monotonic,
    ) -> None:
        self._clock = clock
        self._ip = TokenBucket(ip_per_minute, ip_burst, clock=clock)
        self._submitter = TokenBucket(submitter_per_minute, submitter_burst, clock=clock)

    def check(self, *, ip: str | None, submitter_key: str | None) -> RateLimitDecision:
        now = self._clock()
        ip_wait = self._ip.retry_after(ip, now) if ip else 0.0
        key_wait = (
            self._submitter.retry_after(submitter_key, now) if submitter_key else 0.0
        )
        wait = max(ip_wait, key_wait)
        if wait > 0.0:
            return RateLimitDecision(allowed=False, retry_after=max(1, math.ceil(wait)))
        # Nothing was consumed while probing, so a rejection never burns a
        # token from the bucket that still had room.
        if ip:
            self._ip.consume(ip, now)
        if submitter_key:
            self._submitter.consume(submitter_key, now)
        return RateLimitDecision(allowed=True)


def build_submission_limiter(config: Settings) -> SubmissionRateLimiter:
    return SubmissionRateLimiter(
        ip_per_minute=config.rate_limit_ip_per_minute,
        ip_burst=config.rate_limit_ip_burst,
        submitter_per_minute=config.rate_limit_submitter_per_minute,
        submitter_burst=config.rate_limit_submitter_burst,
    )


class SubmissionRateLimitMiddleware(BaseHTTPMiddleware):
    """Reject over-budget submissions before the body is read or staged."""

    async def dispatch(
        self, request: Request, call_next: RequestResponseEndpoint
    ) -> Response:
        if request.method != "POST" or request.url.path not in SUBMISSION_PATHS:
            return await call_next(request)

        # Test runs post hundreds of tasks from one TestClient address; the
        # suite disables the limiter and its tests enable it explicitly.
        if settings.app_env == "test":
            return await call_next(request)

        if not getattr(request.app.state, "rate_limit_enabled", False):
            return await call_next(request)
        limiter: SubmissionRateLimiter | None = getattr(
            request.app.state, "rate_limiter", None
        )
        if limiter is None:
            return await call_next(request)

        client_ip = request.client.host if request.client else None
        decision = limiter.check(
            ip=client_ip,
            submitter_key=request.headers.get("X-Submitter-Key"),
        )
        if not decision.allowed:
            metrics_mod.inc_counter("vibecheck_rate_limited_total")
            return JSONResponse(
                status_code=429,
                content={
                    "detail": {
                        "error_code": RATE_LIMITED,
                        "error_message": get_error_message(RATE_LIMITED),
                    }
                },
                headers={"Retry-After": str(decision.retry_after)},
            )
        return await call_next(request)
